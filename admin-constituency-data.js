// Get all constituencies
export function getAllConstituencies() {
    return Object.keys(constituencyIslandMapping);
}

// Get islands for a specific constituency
export function getIslandsForConstituency(constituency) {
    if (!constituency) return [];
    return constituencyIslandMapping[constituency] || [];
}

// Get constituency for a specific island
export function getConstituencyForIsland(island) {
    if (!island) return null;
    for (const [constituency, islands] of Object.entries(constituencyIslandMapping)) {
        if (islands.includes(island)) {
            return constituency;
        }
    }
    return null;
}

// Get all unique islands
export function getAllIslands() {
    const allIslands = new Set();
    Object.values(constituencyIslandMapping).forEach(islands => {
        islands.forEach(island => allIslands.add(island));
    });
    return Array.from(allIslands).sort();
}


